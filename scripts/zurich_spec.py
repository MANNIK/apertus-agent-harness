from __future__ import annotations

from dataclasses import dataclass


@dataclass
class Tpl:
    key: str
    cat: str                    # categoria (usata dai report)
    q: dict[str, str]           # domanda per lingua: de, fr, it, en
    params: str                 # SQL che restituisce i candidati (una colonna per parametro)
    gold: str                   # query gold
    order: bool = False         # l'ordine delle righe conta (la domanda chiede un ordinamento)
    trap: str | None = None     # tipo di trappola, se c'è
    n: int = 3                  # istanze per modello
    tie: str | None = None      # SQL che restituisce TRUE se la risposta è unica (nessun pareggio in testa)


def T(key, cat, de, fr, it, en, params, gold, **kw) -> Tpl:
    return Tpl(key, cat, {"de": de, "fr": fr, "it": it, "en": en}, params, gold, **kw)


